"""Explicit rolling checkpoints; lazy torch import, no changes to optimization."""
import json
import os
import shutil
import uuid
from pathlib import Path
from .common import inside, read_json, write_json


def snapshot_hook(state, cpu):
    """Preserve inherited slots and dynamic fields, excluding process-local bindings."""
    values = dict(vars(state)) if hasattr(state, '__dict__') else {}
    for cls in reversed(type(state).__mro__):
        slots = cls.__dict__.get('__slots__', ())
        if isinstance(slots, str):
            slots = (slots,)
        for name in slots:
            if name not in {'__dict__', '__weakref__'} and hasattr(state, name):
                values[name] = getattr(state, name)
    excluded = {'process_group', 'param_state', 'param_to_name', 'excluded_parameter_ids'}
    return {name: cpu(value) for name, value in values.items() if name not in excluded}


def publish(staging, root, step):
    """Publish one complete directory, then retire the previous owned generation."""
    root, staging = Path(root), Path(staging)
    final = root / f'step-{step:08d}'
    latest = root / 'latest'
    previous = latest.resolve() if latest.is_symlink() else None
    if latest.exists() and not latest.is_symlink():
        raise ValueError('latest must be our generation symlink')
    if not (staging/'manifest.json').is_file() or final.exists():
        raise ValueError('Uncommitted or duplicate checkpoint generation')
    os.replace(staging, final)
    temporary = root / ('.latest-' + uuid.uuid4().hex)
    temporary.symlink_to(final.name, target_is_directory=True)
    os.replace(temporary, latest)
    if previous and previous != final:
        if previous.parent != root.resolve() or not previous.name.startswith('step-'):
            raise ValueError('Refusing to delete unrelated checkpoint path')
        shutil.rmtree(previous)
    return final


def save_if_due(local):
    runtime = Path(__file__).resolve().parents[1]
    recipe = read_json(runtime/'recipe.json')
    policy = recipe.get('checkpoint_policy')
    if not isinstance(policy, dict) or policy.get('mode') != 'rolling':
        return
    step = local['update_step']
    if step <= 0 or step % policy['every_updates']:
        return
    import torch
    import torch.distributed as dist
    import random
    import numpy as np
    from . import bridge
    method = read_json(runtime/'method.json')
    parent = inside(Path(os.environ['GLVAL_OUTPUT']), policy.get('root', 'checkpoints'))
    root = parent/method['id']/f"seed-{local['args'].seed}"
    root.mkdir(parents=True,exist_ok=True)
    rank,world = dist.get_rank(),dist.get_world_size()
    token=[uuid.uuid4().hex if rank==0 else None];dist.broadcast_object_list(token,src=0)
    staging = root/('.writing-'+token[0]);staging.mkdir(exist_ok=True)
    torch.cuda.synchronize()
    def cpu(v):
        if torch.is_tensor(v):return v.detach().cpu()
        if isinstance(v,dict):return {k:cpu(x) for k,x in v.items()}
        if isinstance(v,list):return [cpu(x) for x in v]
        if isinstance(v,tuple):return tuple(cpu(x) for x in v)
        return v
    error=None
    try:
        state=bridge._observation['state']
        # Group and parameter-name mapping are regenerated by hook registration.
        hook=snapshot_hook(state,cpu)
        torch.save({'optimizer':cpu(local['optimizer'].state_dict()),
                    'scheduler':cpu(local['scheduler'].state_dict()),'hook_state':hook,
                    'rng':{'torch':torch.get_rng_state(),'cuda':torch.cuda.get_rng_state(),
                           'numpy':np.random.get_state(),'python':random.getstate()},
                    'update_step':step,'global_step':local['global_step'],
                    'tokens_seen':local['tokens_seen'],'rank':rank,'world_size':world},
                   staging/f'rank-{rank}.pt')
        if rank==0:
            model=local['model'].module
            torch.save(cpu(model.state_dict()),staging/'model.pt')
            model.config.to_json_file(staging/'model_config.json')
            write_json(staging/'training_config.json',{'recipe':recipe,'method':method,'args':vars(local['args'])})
    except Exception as e:error=f'rank{rank}: {type(e).__name__}: {e}'
    errors=[None]*world;dist.all_gather_object(errors,error)
    if any(errors):raise RuntimeError(f'Checkpoint write failed; previous latest retained: {errors}')
    result=[None]
    if rank==0:
        try:
            files=[{'name':p.name,'bytes':p.stat().st_size} for p in staging.iterdir()]
            write_json(staging/'manifest.json',{'status':'complete','update_step':step,'world_size':world,
                'files':files,'contains':['model','per-rank optimizer','scheduler','EF/predictor','RNG','training_config'],
                'limitations':['Data iterator and DDP reducer layout are not serialized; this scaffold does not provide exact stream resume.']})
            final=publish(staging,root,step)
            output=Path(os.environ['GLVAL_OUTPUT']);write_json(output/'checkpoint-latest.json',{'path':str(root/'latest'),'generation':str(final),'update_step':step})
            with (output/'checkpoint-events.jsonl').open('a') as f:f.write(json.dumps({'update_step':step,'path':str(root/'latest')})+'\n')
            print(f'Rolling checkpoint committed step{step}: {root}/latest',flush=True)
        except Exception as e:result[0]=f'{type(e).__name__}: {e}'
    dist.broadcast_object_list(result,src=0)
    if result[0]:raise RuntimeError(result[0])
    dist.barrier()
